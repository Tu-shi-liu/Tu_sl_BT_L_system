void RGB_Init(void)
{
    PWM_Init();
    RGB_SetColor(0, 0, 0);
}

void RGB_SetColor(uint8_t r, uint8_t g, uint8_t b)
{
    PWM_SetDuty(PWM_CH_RED,   999 - (uint16_t)(r * 999 / 255));
    PWM_SetDuty(PWM_CH_GREEN, 999 - (uint16_t)(g * 999 / 255));
    PWM_SetDuty(PWM_CH_BLUE,  999 - (uint16_t)(b * 999 / 255));
}

/* 根据色相设置颜色 */
void RGB_SetHue(uint16_t hue)
{
    hue = hue % 360;
    uint8_t r = hue_rgb_table[hue][0];
    uint8_t g = hue_rgb_table[hue][1];
    uint8_t b = hue_rgb_table[hue][2];
    RGB_SetColor(r, g, b);
}

/* 彩虹渐变任务 */
void RGB_RainbowTask(void)
{
    static uint16_t hue = 0;
    RGB_SetHue(hue);
    hue += 2;
    if (hue >= 360) hue = 0;
}

/* 呼吸灯任务 */
void RGB_BreathTask(void)
{
    static uint8_t index = 0;
    uint8_t brightness = breath_table[index];
    RGB_SetColor(brightness, brightness, brightness);
    index += 1; 
    if (index >= 128) {
        index = 0;
    }
}
